// Bilingual UI dictionary (Arabic first — the app's main audience is Arabic
// speakers — with English kept complete).
//
// The module is deliberately pure (no Svelte runes) so the dictionaries and the
// plural logic can be unit-tested in Node; the reactive wrapper lives in
// lib/lang.svelte.js.
//
// Entries are either a plain string or a CLDR plural map
// ({ zero, one, two, few, many, other }) resolved from the `n` parameter.

export const LANGS = [
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' }
];

export const DEFAULT_LANG = 'ar';
export const LANG_KEY = 'studyos.lang';

export function normalizeLang(code) {
  return LANGS.some((l) => l.code === code) ? code : DEFAULT_LANG;
}

export function dirFor(lang) {
  return LANGS.find((l) => l.code === normalizeLang(lang))?.dir || 'ltr';
}

export function isRtl(lang) {
  return dirFor(lang) === 'rtl';
}

// --- plurals ----------------------------------------------------------------

// CLDR plural category for the counts this app shows (cards, pages, items).
export function pluralCategory(lang, n) {
  const count = Math.abs(Number(n) || 0);
  if (lang === 'ar') {
    if (count === 0) return 'zero';
    if (count === 1) return 'one';
    if (count === 2) return 'two';
    const r = count % 100;
    if (r >= 3 && r <= 10) return 'few';
    if (r >= 11 && r <= 99) return 'many';
    return 'other';
  }
  return count === 1 ? 'one' : 'other';
}

export function plural(lang, forms, n) {
  if (typeof forms === 'string') return forms;
  const cat = pluralCategory(lang, n);
  return forms[cat] ?? forms.other ?? forms.one ?? '';
}

function interpolate(text, params) {
  return String(text).replace(/\{(\w+)\}/g, (m, key) => (params[key] ?? '') === '' ? '' : String(params[key]));
}

// --- translate --------------------------------------------------------------

export function translate(lang, key, params = {}) {
  const code = normalizeLang(lang);
  const entry = DICT[code]?.[key] ?? DICT.en[key];
  if (entry === undefined) return key;
  const text = typeof entry === 'object' ? plural(code, entry, params.n ?? params.count ?? 0) : entry;
  return interpolate(text, params);
}

export function hasKey(lang, key) {
  return DICT[normalizeLang(lang)]?.[key] !== undefined;
}

export function dictKeys(lang) {
  return Object.keys(DICT[normalizeLang(lang)] || {}).sort();
}

// --- language plumbing ------------------------------------------------------

export function loadLang(storage = globalThis.localStorage) {
  try {
    const raw = storage?.getItem(LANG_KEY);
    return raw ? normalizeLang(raw) : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function saveLang(lang, storage = globalThis.localStorage) {
  try {
    storage?.setItem(LANG_KEY, normalizeLang(lang));
  } catch {
    /* private mode: the session still switches, it just will not persist */
  }
  return normalizeLang(lang);
}

// What a document element should look like for a language (used on mount and by
// the pre-mount snippet in index.html so there is no flash of the wrong dir).
export function docAttrsFor(lang) {
  const code = normalizeLang(lang);
  return { lang: code, dir: dirFor(code), title: translate(code, 'app.title') };
}

export function applyDocumentLang(lang, doc = globalThis.document) {
  if (!doc?.documentElement) return;
  const attrs = docAttrsFor(lang);
  doc.documentElement.lang = attrs.lang;
  doc.documentElement.dir = attrs.dir;
  doc.title = attrs.title;
}

// Month / weekday names follow the chosen language (Intl, so Arabic gets Arabic
// month and day names) while digits stay Latin for numbers the user typed.
export function localeFor(lang) {
  return normalizeLang(lang) === 'ar' ? 'ar-u-nu-latn' : 'en';
}

export function formatDate(lang, iso, opts = { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }) {
  const [y, m, d] = String(iso || '').split('-').map(Number);
  if (!y || !m || !d) return String(iso || '');
  try {
    return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString(localeFor(lang), { ...opts, timeZone: 'UTC' });
  } catch {
    return String(iso || '');
  }
}

export function formatMonth(lang, iso) {
  return formatDate(lang, `${String(iso).slice(0, 7)}-01`, { month: 'long', year: 'numeric' });
}

export function weekdayShort(lang, dow) {
  // 0 = Sunday, matching lib/recurrence.js dayOfWeek.
  const base = Date.UTC(2024, 0, 7 + (dow % 7)); // 2024-01-07 was a Sunday
  try {
    return new Date(base).toLocaleDateString(localeFor(lang), { weekday: 'short', timeZone: 'UTC' });
  } catch {
    return String(dow);
  }
}

// "Every 2 weeks on Sun, Tue · ends 2026-03-01" — the localized counterpart of
// lib/recurrence.js describeRule (which stays the machine/test-facing version).
export function describeRuleText(lang, rule, t) {
  if (!rule) return '';
  const interval = Math.max(1, Number(rule.interval) || 1);
  const freq = rule.freq || 'daily';
  let text;
  if (freq === 'weekly') {
    const days = (rule.daysOfWeek || []).slice().sort().map((d) => weekdayShort(lang, d)).join('، ');
    if (interval > 1) text = t('rule.weeklyN', { n: interval, days });
    else text = days ? t('rule.weeklyDays', { days }) : t('rule.weekly');
  } else if (freq === 'monthly') {
    text = interval > 1
      ? t('rule.monthlyN', { n: interval, day: rule.dayOfMonth ?? 1 })
      : t('rule.monthly', { day: rule.dayOfMonth ?? 1 });
  } else {
    text = interval > 1 ? t('rule.dailyN', { n: interval }) : t('rule.daily');
  }
  return rule.endDate ? `${text}${t('rule.endsOn', { date: rule.endDate })}` : text;
}

