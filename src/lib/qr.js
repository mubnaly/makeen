import QRCode from 'qrcode';

/**
 * Generate a PNG Data URL QR code for a given text or URL.
 * @param {string} text
 * @param {number} width
 * @returns {Promise<string>}
 */
export async function generateQrDataUrl(text, width = 240) {
  if (!text || typeof text !== 'string') return '';
  try {
    return await QRCode.toDataURL(text.trim(), {
      width,
      margin: 2,
      color: {
        dark: '#0f172a',
        light: '#ffffff'
      },
      errorCorrectionLevel: 'M'
    });
  } catch (err) {
    console.error('QR code generation failed:', err);
    return '';
  }
}

/**
 * Build a structured shareable text for a project (title, links, resources).
 * @param {object} project
 * @param {Array} videos
 * @param {Array} docs
 * @returns {string}
 */
export function buildProjectShareSummary(project, videos = [], docs = []) {
  if (!project) return '';
  const lines = [];
  lines.push(`📚 ${project.name}`);
  if (project.description) {
    lines.push(project.description);
  }
  lines.push('');

  // Collect YouTube and video links
  const collectedVideos = [];
  const seenUrls = new Set();

  for (const vid of project.videos || []) {
    const v = videos.find((item) => item.id === vid);
    if (v && v.url && !seenUrls.has(v.url)) {
      seenUrls.add(v.url);
      collectedVideos.push({ title: v.title || v.id, url: v.url });
    }
  }

  for (const folder of project.folders || []) {
    for (const item of folder.items || []) {
      if ((item.type === 'video' || item.type === 'youtube') && item.url && !seenUrls.has(item.url)) {
        seenUrls.add(item.url);
        collectedVideos.push({ title: item.title, url: item.url });
      }
    }
  }

  if (project.channelVideos && Array.isArray(project.channelVideos)) {
    for (const cv of project.channelVideos) {
      const url = cv.url || (cv.id ? `https://www.youtube.com/watch?v=${cv.id}` : '');
      if (url && !seenUrls.has(url)) {
        seenUrls.add(url);
        collectedVideos.push({ title: cv.title, url });
      }
    }
  }

  if (collectedVideos.length > 0) {
    lines.push(`🎬 Videos (${collectedVideos.length}):`);
    for (const cv of collectedVideos) {
      lines.push(`- ${cv.title}: ${cv.url}`);
    }
    lines.push('');
  }

  // Collect PDFs
  const collectedDocs = [];
  for (const docId of project.docs || []) {
    const d = docs.find((item) => item.id === docId);
    if (d) collectedDocs.push(d.title || d.id);
  }
  for (const folder of project.folders || []) {
    for (const item of folder.items || []) {
      if (item.type === 'pdf') collectedDocs.push(item.title);
    }
  }

  if (collectedDocs.length > 0) {
    lines.push(`📄 Documents (${collectedDocs.length}):`);
    for (const cd of collectedDocs) {
      lines.push(`- ${cd}`);
    }
    lines.push('');
  }

  lines.push(`Generated by StudyOS • ${new Date().toLocaleDateString()}`);
  return lines.join('\n');
}
